def self_test():
    failures = 0
    for i, (source, expected) in enumerate(COMBINATOR_SELF_TESTS):
        got = [call for _, call in combinator_allocations(source)]
        if got != expected:
            failures += 1
            print(f"combinator self-test {i} failed: expected {expected}, got {got}\n{source}")
    for i, (source, expected) in enumerate(CLOSURE_SELF_TESTS):
        got = [call for _, call in closure_panics(source)]
        if got != expected:
            failures += 1
            print(f"closure self-test {i} failed: expected {expected}, got {got}\n{source}")
    cases = [(src, exp, False) for src, exp in SELF_TESTS]
    cases += [(src, exp, True) for src, exp in STRICT_SELF_TESTS]
    for i, (source, expected, strict) in enumerate(cases):
        got = [name for _, name in scan("self-test.rs", source, internal_types([source]), None, strict)]
        if got != expected:
            failures += 1
            print(f"self-test {i} failed: expected {expected}, got {got}\n{source}")
    total = len(cases) + len(CLOSURE_SELF_TESTS) + len(COMBINATOR_SELF_TESTS)
    print(f"{total - failures}/{total} self-tests passed")
    return failures == 0


def main(argv):
    args = argv[1:]
    if "--self-test" in args:
        return 0 if self_test() else 1
    root = args[0] if args else Path(__file__).resolve().parent.parent
    failures = check(root)
    for f in failures:
        print(f)
    if failures:
        print(f"{len(failures)} problem(s) with #[track_caller] on the public API")
        return 1
    print("all public functions carry #[track_caller]")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
