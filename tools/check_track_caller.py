FN_RE = re.compile(r"^\s*(?P<vis>pub(\([^)]*\))?\s+)?(const\s+|unsafe\s+|async\s+|extern\s+\"[^\"]*\"\s+)*fn\s+(?P<name>[\w$]+)")
# `fn` at the end of a line, with the name on the next one.
FN_HEAD_RE = re.compile(r"^\s*(?P<vis>pub(\([^)]*\))?\s+)?(const\s+|unsafe\s+|async\s+|extern\s+\"[^\"]*\"\s+)*fn\s*$")
NAME_RE = re.compile(r"^\s*(?P<name>[\w$]+)")
# The attribute itself, alone on its line apart from a trailing comment.
ATTR_RE = re.compile(r"^#\[\s*track_caller\s*\]$")
TRAIT_RE = re.compile(r"^\s*pub\s+(unsafe\s+)?trait\s+\w+")
IMPL_RE = re.compile(r"^\s*(unsafe\s+)?impl\b(?P<rest>.*)")
CFG_TEST_RE = re.compile(r"^\s*#\[cfg\((test|doctest)\)\]")


def strip_comment(line):
    """The line without a trailing `//` comment (string literals with `//` are rare enough)."""
    i = line.find("//")
    return line if i < 0 else line[:i]


def brace_delta(line):
    code = strip_comment(line)
    code = re.sub(r"'(\\.|[^'\\])'", "", code)  # char literals such as '{'
    code = re.sub(r'"(\\.|[^"\\])*"', "", code)
    return code.count("{") - code.count("}")


INTERNAL_TYPE_RE = re.compile(
    r"^\s*(pub\((crate|super)\)\s+)?(struct|enum|union)\s+(?P<name>\w+)"
)


def internal_types(texts):
    """Names of the structs and enums that aren't `pub` anywhere in the crate."""
    internal, public = set(), set()
    for text in texts:
        for line in text.splitlines():
            m = INTERNAL_TYPE_RE.match(line)
            if m:
                internal.add(m.group("name"))
            m = re.match(r"^\s*pub\s+(struct|enum|union)\s+(\w+)", line)
            if m:
                public.add(m.group(2))
    return internal - public


def impl_self_type(rest):
    """The self type name of an inherent `impl<..> Type<..>`."""
    rest = rest.strip()
    if rest.startswith("<"):
        depth = 0
        for i, c in enumerate(rest):
            depth += c == "<"
            depth -= c == ">"
            if depth == 0:
                rest = rest[i + 1:]
                break
    m = re.match(r"\s*([\w:]+)", rest)
    return m.group(1).split("::")[-1] if m else None


def impl_trait(rest):
    """The trait name of `impl<..> Trait<..> for Type`, or None for an inherent impl."""
    # Drop the generic parameters right after `impl`.
    rest = rest.strip()
    if rest.startswith("<"):
        depth = 0
        for i, c in enumerate(rest):
            depth += c == "<"
            depth -= c == ">"
            if depth == 0:
                rest = rest[i + 1:]
                break
    m = re.match(r"\s*([\w:$]+)", rest)
    if not m or not re.search(r"\bfor\b", rest):
        return None
    return m.group(1).split("::")[-1]


def fn_at(lines, i):
    """`(visibility, name)` of the function whose `fn` keyword is on line `i`, or None."""
    m = FN_RE.match(lines[i])
    if m:
        return m.group("vis"), m.group("name")
    m = FN_HEAD_RE.match(lines[i])
    if m and i + 1 < len(lines):
        name = NAME_RE.match(lines[i + 1])
        if name:
            return m.group("vis"), name.group("name")
    return None


def has_attr(lines, i):
    """Whether the attributes right above line `i` include `#[track_caller]`. Comments and doc
    comments among them are skipped; text in them never counts as the attribute."""
    j = i - 1
    in_attr = False
    while j >= 0:
        s = lines[j].strip()
        if in_attr:
            if s.startswith("#["):
                in_attr = False
        elif s.startswith("//"):
            pass
        elif s.startswith(("#[", "#!")):
            if ATTR_RE.match(strip_comment(s).strip()):
                return True
        elif s.endswith((")]", "]")) and not s.endswith("];"):
            in_attr = True  # the end of a multi-line attribute
        else:
            break
        j -= 1
    return False


def scan(path, text, internal=frozenset(), used=None, strict=False):
    """The `(line number, function name)` of every function that misses the attribute.

    `internal` holds the names of crate-internal types, whose inherent impls are skipped. The
    `ALLOWED` entries that excuse a function are added to `used`. `strict` also requires the
    attribute on `pub(crate)` functions.
    """
    lines = text.splitlines()
    missing = []
    # Stack of (kind, depth at which the block's body lives): kind is "trait", "stdop", "skip",
    # "internal" (an inherent impl of a crate-internal type) or "other".
    stack = []
    depth = 0
    pending = None  # a block kind waiting for its opening brace
    skip_next_block = False
    for i, line in enumerate(lines):
        s = line.strip()
        if CFG_TEST_RE.match(line):
            skip_next_block = True
            continue
        in_skip = any(kind in ("skip", "internal") for kind, _ in stack)
        m = fn_at(lines, i)
        if m and not in_skip:
            top = stack[-1][0] if stack else None
            top_depth = stack[-1][1] if stack else 0
            directly_inside = top is not None and depth == top_depth
            vis, name = m
            visibility = vis.strip() if vis else ""
            needs = visibility == "pub" or (strict and visibility == "pub(crate)")
            if directly_inside and top in ("trait", "stdop"):
                needs = True
            if needs and (path, name) in ALLOWED:
                if used is not None:
                    used.add((path, name))
            elif needs and not has_attr(lines, i):
                missing.append((i + 1, name))
        # Block kinds for the next opening brace.
        if pending is None:
            if skip_next_block and re.match(r"^\s*(pub\s+)?mod\s+\w+", line):
                pending = "skip"
            elif re.match(r"^\s*(pub\((crate|super)\)\s+)?mod\s+\w+\s*\{", line):
                pending = "internal"  # an inline module that isn't `pub`
            elif TRAIT_RE.match(line):
                pending = "trait"
            elif IMPL_RE.match(line):
                trait = impl_trait(IMPL_RE.match(line).group("rest"))
                is_op = trait is not None and (trait in STD_OPS or trait.startswith("$"))
                rest = IMPL_RE.match(line).group("rest")
                if is_op:
                    pending = "stdop"
                elif trait is None and impl_self_type(rest) in internal:
                    pending = "internal"
                else:
                    pending = "other"
            elif re.match(r"^\s*(pub(\([^)]*\))?\s+)?trait\s+\w+", line):
                pending = "other"  # a private trait
        if skip_next_block and s and not s.startswith(("#", "//")) and pending != "skip":
            if not re.match(r"^\s*(pub\s+)?mod\s+\w+", line):
                skip_next_block = False
        delta = brace_delta(line)
        if pending is not None and delta > 0:
            stack.append((pending, depth + 1))
            if pending == "skip":
                skip_next_block = False
            pending = None
        elif pending is not None and (s.endswith(";") or s.endswith("{}")):
            pending = None  # `mod x;` or a one-line item such as `pub trait Marker: Sealed {}`
        depth += delta
        while stack and depth < stack[-1][1]:
            stack.pop()
    return missing


EXEC_RE = re.compile(r"\b(?:backend::|cpu::|rocm::)?exec\(")
# Calls that panic for a failure (or report a device's failure with a panic) where they are.
CLOSURE_PANIC_RE = re.compile(
    r"\bexpect\(|\.unwrap\(\)|\bpanic!|\bunreachable!|\.raise\(\)"
    r"|\bbackend::(?:try_)?(?:copy|fill)\(|\bbackend::(?:write_host|read_host|read_bytes)\b"
)


def code_only(text):
    """`text` with comments, string and char literals blanked, keeping lines and columns."""
    out = []
    for line in text.splitlines():
        code = strip_comment(line)
        code = re.sub(r"'(\\.|[^'\\])'", lambda m: " " * len(m.group(0)), code)
        code = re.sub(r'"(\\.|[^"\\])*"', lambda m: '"' + " " * (len(m.group(0)) - 2) + '"', code)
        out.append(code)
    return "\n".join(out)


def closure_panics(text):
    """`(line number, call)` of every panicking call inside the arguments of an execution lock's
    `exec(...)` (a closure)."""
    code = code_only(text)
    found = []
    for m in EXEC_RE.finditer(code):
        start = m.end()
        depth, end = 1, start
        while end < len(code) and depth:
            depth += code[end] == "("
            depth -= code[end] == ")"
            end += 1
        for p in CLOSURE_PANIC_RE.finditer(code, start, end - 1):
            found.append((code.count("\n", 0, p.start()) + 1, p.group(0)))
    return found


# A combinator whose argument is a closure, up to the closure's parameters.
COMBINATOR_RE = re.compile(
    r"\.(?:then|map|and_then|or_else|unwrap_or_else|map_or_else|map_err|filter_map|flat_map"
    r"|find_map|for_each|get_or_insert_with)\(\s*(?:move\s+)?\|"
)
# The allocation and transfer primitives that panic for a device's failure where they are.
ALLOCATION_RE = re.compile(r"\b(?:empty_on|convert_data|on_device|\w*workspace)\(")


def combinator_allocations(text):
    """`(line number, call)` of every allocation or transfer primitive inside the closure of a
    combinator such as `.then(|| ..)` or `.map(|x| ..)`."""
    code = code_only(text)
    found = []
    for m in COMBINATOR_RE.finditer(code):
        start = m.end()
        depth, end = 1, start
        while end < len(code) and depth:
            depth += code[end] == "("
            depth -= code[end] == ")"
            end += 1
        for p in ALLOCATION_RE.finditer(code, start, end - 1):
            found.append((code.count("\n", 0, p.start()) + 1, p.group(0)))
    return found


def check(root):
    root = Path(root)
    failures = []
    used = set()
    for crate in CRATES:
        paths = sorted((root / crate).rglob("*.rs"))
        internal = internal_types(p.read_text() for p in paths)
        for path in paths:
            rel = path.relative_to(root).as_posix()
            strict = rel.startswith(STRICT) and rel not in STRICT_EXEMPT
            if not strict and (rel.startswith(SKIP_DIRS) or rel.endswith("_tests.rs")):
                continue
            text = path.read_text()
            for line, name in scan(rel, text, internal, used, strict):
                failures.append(f"{rel}:{line}: `{name}` lacks #[track_caller]")
            for line, call in closure_panics(text):
                failures.append(
                    f"{rel}:{line}: `{call}` panics inside an execution lock's closure, which "
                    "hides the caller's location; return the failure and report it after"
                )
            for line, call in combinator_allocations(text):
                failures.append(
                    f"{rel}:{line}: `{call}` allocates or transfers inside a combinator's "
                    "closure, which hides the caller's location; use an explicit `if` or `match`"
                )
    for path, name in sorted(set(ALLOWED) - used):
        failures.append(f"{path}: the ALLOWED entry for `{name}` excuses no function; remove it")
    return failures


