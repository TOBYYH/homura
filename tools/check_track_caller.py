#!/usr/bin/env python3
"""Checks that the public API of homura and homura-models carries `#[track_caller]`.

Programming errors panic (shape, dtype, device, index and option checks), and the panic should
point at the caller's line, not at homura's internals. The rule: every function of the public
API is annotated, so that a panic anywhere below it reports the user's call. This script is the
static gate; `tests/panic_location.rs` checks at run time that the locations really arrive.

A function must be annotated when it is
- a `pub fn` (any `pub fn`, `pub const fn`, `pub unsafe fn`; not `pub(crate)` or `pub(super)`),
  including methods of impl blocks and functions generated by `macro_rules!`;
- a method declared or provided by a `pub trait` (the attribute on the declaration applies to
  every implementation);
- a method of an implementation of a standard operator trait (`Add`, `Neg`, `AddAssign`, `Index`,
  ..., or a trait named by a macro metavariable such as `$Trait`) or of `Sum` / `Product`, whose
  declarations in `std` don't carry the attribute.

The dispatch layer (`src/backend/mod.rs`) and the ROCm backend (`src/backend/rocm/`, including
code behind `#[cfg(feature = "rocm")]`) are checked more strictly: every `pub(crate) fn` there
must carry the attribute too, since operations call them on the way to checks that panic for the
user's arguments (index ranges, missing devices). The generated bindings (`ffi.rs`) are exempt.

Not checked: methods of inherent impls of crate-internal types (declared `pub(crate)` or without
`pub`, so their `pub fn`s aren't reachable from outside); the rest of `src/backend/` (kernels,
whose panics are homura bugs, except for the few that check user input, such as index ranges,
which carry the attribute and are covered by the run-time test); unit test files and modules;
and the functions in `ALLOWED` below, each with its reason. Neither are the other internal
functions between an entry point and a check: the run-time test covers those.

Closures don't pass `#[track_caller]` on, so a panic inside one reports the closure's line
(review round 124, R149). The closures of the execution locks (`exec(...)`, `backend::exec(...)`,
`cpu::exec(...)`) are where device operations run, so in the checked files they must not
contain a panicking call: `expect(...)`, `.unwrap()`, `panic!`, `.raise()`, or a device data
operation that reports its own failures (`backend::copy`, `backend::try_fill`, ...). They return
the failure instead (`backend::copy_unreported`, the ROCm `Result`s), reported after the closure.

For the same reason, the closures passed to combinators (`.then(..)`, `.map(..)`, `.and_then(..)`,
`.unwrap_or_else(..)`, ...) in the checked files must not call homura's internal allocation and
transfer primitives, whose failures on a device (out of memory, a failed upload) panic where
they are: `empty_on(..)`, `convert_data(..)`, `on_device(..)` and the workspace helpers
(`..workspace(..)`); an explicit `if` / `match` keeps the caller's location (review round 131,
R155). This covers the primitives only: a public tensor operation called inside such a closure
also reports the closure's line when it fails, which the run-time test has to find.

The scanner reads rustfmt-formatted source line by line rather than parsing Rust: a function
starts at a line with `fn` (its name on that line or the next), and only an attribute line
`#[track_caller]` right above it, among its other attributes, comments and doc comments, counts.
Text in comments and doc comments never does.

Usage: check_track_caller.py [--self-test] [ROOT]
"""

