#!/usr/bin/env python3
"""Checks that the public API of homura and homura-models carries `#[track_caller]`.

Programming errors panic (shape, dtype, device, index and option checks), and the panic should
point at the caller's line, not at homura's internals. The rule: every function of the public
API is annotated, so that a panic anywhere below it reports the user's call. This script is the
static gate; `tests/panic_location.rs` checks at run time that the locations really arrive.

A function must be annotated when it is
- a `pub fn` (any `pub fn`, `pub const fn`, `pub unsafe fn`; not `pub(crate)` or `pub(super)`),
  including methods of impl blocks and functions generated by `macro_rules!`;
- a method declared or provided by a `pub trait` (the attribute on the declaration applies to
  every implementation);
- a method of an implementation of a standard operator trait (`Add`, `Neg`, `AddAssign`, `Index`,
  ..., or a trait named by a macro metavariable such as `$Trait`) or of `Sum` / `Product`, whose
  declarations in `std` don't carry the attribute.

Not checked: methods of inherent impls of crate-internal types (declared `pub(crate)` or without
`pub`, so their `pub fn`s aren't reachable from outside); `src/backend/` (kernels, whose panics
are homura bugs, except for the few that check user input, such as index ranges, which carry the
attribute and are covered by the run-time test); unit test files and modules; and the functions
in `ALLOWED` below, each with its reason. Neither are the internal functions between an entry
point and a check: the run-time test covers those.

The scanner reads rustfmt-formatted source line by line rather than parsing Rust: a function
starts at a line with `fn` (its name on that line or the next), and only an attribute line
`#[track_caller]` right above it, among its other attributes, comments and doc comments, counts.
Text in comments and doc comments never does.

Usage: check_track_caller.py [--self-test] [ROOT]
"""

import re
import sys
from pathlib import Path

# (file relative to the repository root, function name): why it needs no `#[track_caller]`.
CALLBACK = (
    "callback that users implement and homura calls: on the trait declaration the attribute "
    "would apply to the user's implementation and move panics in it to homura's call site"
)
ALLOWED = {
    ("src/dtype.rs", "cast"): "Element::cast: hidden, infallible element conversion of the kernels",
    ("src/autograd/function.rs", "forward"): CALLBACK,
    ("src/autograd/function.rs", "backward"): CALLBACK,
    ("src/nn/module.rs", "parameter"): CALLBACK,
    ("src/nn/module.rs", "buffer"): CALLBACK,
    ("src/nn/module.rs", "module"): CALLBACK,
    ("src/nn/module.rs", "training"): CALLBACK,
    ("src/nn/module.rs", "visit_as"): CALLBACK,
    ("src/nn/module.rs", "is_plain_value"): CALLBACK,
    ("src/nn/module.rs", "visit"): CALLBACK,
    ("src/nn/module.rs", "extra_repr"): CALLBACK,
    ("src/nn/module.rs", "type_name"): CALLBACK,
    ("src/nn/module.rs", "version"): CALLBACK,
    ("src/nn/module.rs", "added_in"): CALLBACK,
    ("src/nn/module.rs", "visit_non_persistent"): CALLBACK,
}

# The source directories of the crates whose API is checked (homura-derive's macros don't panic
# at run time).
CRATES = ("src", "homura-models/src")
SKIP_DIRS = ("src/backend/", "src/autograd/test_support/")
STD_OPS = {
    "Add", "Sub", "Mul", "Div", "Rem", "Neg", "Not",
    "AddAssign", "SubAssign", "MulAssign", "DivAssign", "RemAssign",
    "Index", "IndexMut", "Sum", "Product",
}

FN_RE = re.compile(r"^\s*(?P<vis>pub(\([^)]*\))?\s+)?(const\s+|unsafe\s+|async\s+|extern\s+\"[^\"]*\"\s+)*fn\s+(?P<name>[\w$]+)")
# `fn` at the end of a line, with the name on the next one.
FN_HEAD_RE = re.compile(r"^\s*(?P<vis>pub(\([^)]*\))?\s+)?(const\s+|unsafe\s+|async\s+|extern\s+\"[^\"]*\"\s+)*fn\s*$")
NAME_RE = re.compile(r"^\s*(?P<name>[\w$]+)")
# The attribute itself, alone on its line apart from a trailing comment.
ATTR_RE = re.compile(r"^#\[\s*track_caller\s*\]$")
TRAIT_RE = re.compile(r"^\s*pub\s+(unsafe\s+)?trait\s+\w+")
IMPL_RE = re.compile(r"^\s*(unsafe\s+)?impl\b(?P<rest>.*)")
CFG_TEST_RE = re.compile(r"^\s*#\[cfg\((test|doctest)\)\]")


def strip_comment(line):
    """The line without a trailing `//` comment (string literals with `//` are rare enough)."""
    i = line.find("//")
    return line if i < 0 else line[:i]


def brace_delta(line):
    code = strip_comment(line)
    code = re.sub(r"'(\\.|[^'\\])'", "", code)  # char literals such as '{'
    code = re.sub(r'"(\\.|[^"\\])*"', "", code)
    return code.count("{") - code.count("}")


INTERNAL_TYPE_RE = re.compile(
    r"^\s*(pub\((crate|super)\)\s+)?(struct|enum|union)\s+(?P<name>\w+)"
)


def internal_types(texts):
    """Names of the structs and enums that aren't `pub` anywhere in the crate."""
    internal, public = set(), set()
    for text in texts:
        for line in text.splitlines():
            m = INTERNAL_TYPE_RE.match(line)
            if m:
                internal.add(m.group("name"))
            m = re.match(r"^\s*pub\s+(struct|enum|union)\s+(\w+)", line)
            if m:
                public.add(m.group(2))
    return internal - public


def impl_self_type(rest):
    """The self type name of an inherent `impl<..> Type<..>`."""
    rest = rest.strip()
    if rest.startswith("<"):
        depth = 0
        for i, c in enumerate(rest):
            depth += c == "<"
            depth -= c == ">"
            if depth == 0:
                rest = rest[i + 1:]
                break
    m = re.match(r"\s*([\w:]+)", rest)
    return m.group(1).split("::")[-1] if m else None


def impl_trait(rest):
    """The trait name of `impl<..> Trait<..> for Type`, or None for an inherent impl."""
    # Drop the generic parameters right after `impl`.
    rest = rest.strip()
    if rest.startswith("<"):
        depth = 0
        for i, c in enumerate(rest):
            depth += c == "<"
            depth -= c == ">"
            if depth == 0:
                rest = rest[i + 1:]
                break
    m = re.match(r"\s*([\w:$]+)", rest)
    if not m or not re.search(r"\bfor\b", rest):
        return None
    return m.group(1).split("::")[-1]


def fn_at(lines, i):
    """`(visibility, name)` of the function whose `fn` keyword is on line `i`, or None."""
    m = FN_RE.match(lines[i])
    if m:
        return m.group("vis"), m.group("name")
    m = FN_HEAD_RE.match(lines[i])
    if m and i + 1 < len(lines):
        name = NAME_RE.match(lines[i + 1])
        if name:
            return m.group("vis"), name.group("name")
    return None


def has_attr(lines, i):
    """Whether the attributes right above line `i` include `#[track_caller]`. Comments and doc
    comments among them are skipped; text in them never counts as the attribute."""
    j = i - 1
    in_attr = False
    while j >= 0:
        s = lines[j].strip()
        if in_attr:
            if s.startswith("#["):
                in_attr = False
        elif s.startswith("//"):
            pass
        elif s.startswith(("#[", "#!")):
            if ATTR_RE.match(strip_comment(s).strip()):
                return True
        elif s.endswith((")]", "]")) and not s.endswith("];"):
            in_attr = True  # the end of a multi-line attribute
        else:
            break
        j -= 1
    return False


def scan(path, text, internal=frozenset(), used=None):
    """The `(line number, function name)` of every function that misses the attribute.

    `internal` holds the names of crate-internal types, whose inherent impls are skipped. The
    `ALLOWED` entries that excuse a function are added to `used`.
    """
    lines = text.splitlines()
    missing = []
    # Stack of (kind, depth at which the block's body lives): kind is "trait", "stdop", "skip",
    # "internal" (an inherent impl of a crate-internal type) or "other".
    stack = []
    depth = 0
    pending = None  # a block kind waiting for its opening brace
    skip_next_block = False
    for i, line in enumerate(lines):
        s = line.strip()
        if CFG_TEST_RE.match(line):
            skip_next_block = True
            continue
        in_skip = any(kind in ("skip", "internal") for kind, _ in stack)
        m = fn_at(lines, i)
        if m and not in_skip:
            top = stack[-1][0] if stack else None
            top_depth = stack[-1][1] if stack else 0
            directly_inside = top is not None and depth == top_depth
            vis, name = m
            needs = bool(vis) and vis.strip() == "pub"
            if directly_inside and top in ("trait", "stdop"):
                needs = True
            if needs and (path, name) in ALLOWED:
                if used is not None:
                    used.add((path, name))
            elif needs and not has_attr(lines, i):
                missing.append((i + 1, name))
        # Block kinds for the next opening brace.
        if pending is None:
            if skip_next_block and re.match(r"^\s*(pub\s+)?mod\s+\w+", line):
                pending = "skip"
            elif re.match(r"^\s*(pub\((crate|super)\)\s+)?mod\s+\w+\s*\{", line):
                pending = "internal"  # an inline module that isn't `pub`
            elif TRAIT_RE.match(line):
                pending = "trait"
            elif IMPL_RE.match(line):
                trait = impl_trait(IMPL_RE.match(line).group("rest"))
                is_op = trait is not None and (trait in STD_OPS or trait.startswith("$"))
                rest = IMPL_RE.match(line).group("rest")
                if is_op:
                    pending = "stdop"
                elif trait is None and impl_self_type(rest) in internal:
                    pending = "internal"
                else:
                    pending = "other"
            elif re.match(r"^\s*(pub(\([^)]*\))?\s+)?trait\s+\w+", line):
                pending = "other"  # a private trait
        if skip_next_block and s and not s.startswith(("#", "//")) and pending != "skip":
            if not re.match(r"^\s*(pub\s+)?mod\s+\w+", line):
                skip_next_block = False
        delta = brace_delta(line)
        if pending is not None and delta > 0:
            stack.append((pending, depth + 1))
            if pending == "skip":
                skip_next_block = False
            pending = None
        elif pending is not None and (s.endswith(";") or s.endswith("{}")):
            pending = None  # `mod x;` or a one-line item such as `pub trait Marker: Sealed {}`
        depth += delta
        while stack and depth < stack[-1][1]:
            stack.pop()
    return missing


def check(root):
    root = Path(root)
    failures = []
    used = set()
    for crate in CRATES:
        paths = sorted((root / crate).rglob("*.rs"))
        internal = internal_types(p.read_text() for p in paths)
        for path in paths:
            rel = path.relative_to(root).as_posix()
            if rel.startswith(SKIP_DIRS) or rel.endswith("_tests.rs"):
                continue
            for line, name in scan(rel, path.read_text(), internal, used):
                failures.append(f"{rel}:{line}: `{name}` lacks #[track_caller]")
    for path, name in sorted(set(ALLOWED) - used):
        failures.append(f"{path}: the ALLOWED entry for `{name}` excuses no function; remove it")
    return failures


SELF_TESTS = [
    # (source, expected missing names)
    ("/// Doc.\n#[track_caller]\npub fn ok() {}\npub fn bad() {}\n", ["bad"]),
    ("#[track_caller]\n#[must_use]\npub fn ok() -> u8 { 0 }\n", []),
    ("#[must_use]\n#[track_caller]\npub fn ok() -> u8 { 0 }\n", []),
    ("pub(crate) fn internal() {}\nfn private() {}\n", []),
    ("#[track_caller]\npub fn multi(\n    a: u8,\n    b: u8,\n) {}\n", []),
    ("pub fn\nsplit() {}\n#[track_caller]\npub fn\nsplit_ok() {}\n", ["split"]),
    ("#[allow(\n    clippy::too_many_arguments\n)]\n#[track_caller]\npub fn wrapped() {}\n", []),
    ("#[track_caller]\n#[allow(\n    dead_code\n)]\npub fn wrapped() {}\n", []),
    ("pub const fn c() -> u8 { 0 }\npub unsafe fn u() {}\n", ["c", "u"]),
    ("pub trait T {\n    fn decl(&self);\n    #[track_caller]\n    fn ok(&self);\n"
     "    fn provided(&self) { inner() }\n}\n", ["decl", "provided"]),
    ("trait Private {\n    fn decl(&self);\n}\n", []),
    ("impl std::ops::Add for X {\n    type Output = X;\n    fn add(self, o: X) -> X { o }\n}\n", ["add"]),
    ("impl<T: Into<Y>> AddAssign<T> for X {\n    #[track_caller]\n    fn add_assign(&mut self, o: T) {}\n}\n", []),
    ("impl Index<&str> for X {\n    type Output = u8;\n    fn index(&self, k: &str) -> &u8 { &0 }\n}\n", ["index"]),
    ("impl<'a> Sum<&'a X> for X {\n    fn sum<I: Iterator<Item = &'a X>>(i: I) -> X { X }\n}\n"
     "impl std::iter::Product for X {\n    #[track_caller]\n    fn product<I>(i: I) -> X { X }\n}\n", ["sum"]),
    ("macro_rules! m {\n    ($Trait:ident, $method:ident) => {\n        impl $Trait<&X> for &X {\n"
     "            fn $method(self, rhs: &X) -> X { rhs }\n        }\n    };\n}\n", ["$method"]),
    ("macro_rules! m {\n    ($name:ident) => {\n        impl $name {\n            pub fn setter(self) -> $name { self }\n"
     "        }\n    };\n}\n", ["setter"]),
    ("impl fmt::Display for X {\n    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result { Ok(()) }\n}\n", []),
    ("impl Module for X {\n    fn visit(&self) {}\n}\n", []),
    ("impl X {\n    pub fn method(&self) {\n        let f = |c: char| c == '{';\n    }\n"
     "    pub fn second(&self) {}\n}\n", ["method", "second"]),
    ("#[cfg(test)]\nmod tests {\n    pub fn helper() {}\n}\npub fn after() {}\n", ["after"]),
    ("#[cfg(test)]\n#[path = \"x_tests.rs\"]\nmod tests;\npub fn after() {}\n", ["after"]),
    ("impl X {\n    /// Has `{` in a doc.\n    #[track_caller]\n    pub fn a(&self) {}\n}\n", []),
    ("pub(crate) struct In;\nimpl In {\n    pub fn skipped(&self) {}\n}\n"
     "pub struct Out;\nimpl Out {\n    pub fn checked(&self) {}\n}\n", ["checked"]),
    ("pub(crate) mod sealed {\n    pub trait Sealed {\n        fn f(self);\n    }\n}\n"
     "pub mod open {\n    pub fn g() {}\n}\n", ["g"]),
    ("struct Private<T>(T);\nimpl<T> Private<T> {\n    pub fn skipped(&self) {}\n}\n", []),
    ("/// A doc example:\n/// ```\n/// fn f() {}\n/// ```\npub fn documented() {}\n", ["documented"]),
    # Text in comments and doc comments isn't the attribute (review round 82, R108).
    ("// #[track_caller]\npub fn commented() {}\n", ["commented"]),
    ("/// This function carries #[track_caller].\npub fn doc_text() {}\n", ["doc_text"]),
    ("/// ```\n/// #[track_caller]\n/// fn f() {}\n/// ```\npub fn doc_code() {}\n", ["doc_code"]),
    # A trait with an empty body on one line doesn't make the next impl a trait body.
    ("pub trait Marker: Sealed {}\nimpl Sealed for X {\n    fn f(self) {}\n}\n"
     "impl Marker for X {}\npub fn after() {}\n", ["after"]),
    ("#[must_use] // #[track_caller]\npub fn trailing_text() -> u8 { 0 }\n", ["trailing_text"]),
    ("//! #[track_caller]\n#![allow(dead_code)]\npub fn inner_doc() {}\n", ["inner_doc"]),
    ("/// Mentions #[track_caller].\n#[track_caller]\n// A comment.\n#[must_use]\n"
     "pub fn interleaved() -> u8 { 0 }\n", []),
    ("#[track_caller] // The caller's line.\npub fn trailing_comment() {}\n", []),
    ("impl X {\n    /// #[track_caller]\n    #[allow(\n        dead_code\n    )]\n"
     "    pub fn in_impl(&self) {}\n}\n", ["in_impl"]),
]


def self_test():
    failures = 0
    for i, (source, expected) in enumerate(SELF_TESTS):
        got = [name for _, name in scan("self-test.rs", source, internal_types([source]))]
        if got != expected:
            failures += 1
            print(f"self-test {i} failed: expected {expected}, got {got}\n{source}")
    print(f"{len(SELF_TESTS) - failures}/{len(SELF_TESTS)} self-tests passed")
    return failures == 0


def main(argv):
    args = argv[1:]
    if "--self-test" in args:
        return 0 if self_test() else 1
    root = args[0] if args else Path(__file__).resolve().parent.parent
    failures = check(root)
    for f in failures:
        print(f)
    if failures:
        print(f"{len(failures)} problem(s) with #[track_caller] on the public API")
        return 1
    print("all public functions carry #[track_caller]")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
