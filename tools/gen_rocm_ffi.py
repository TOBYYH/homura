#!/usr/bin/env python3
"""Generates src/backend/rocm/ffi.rs from csrc/homura_rocm.h with the bindgen CLI.

usage: tools/gen_rocm_ffi.py           (rewrite the file)
       tools/gen_rocm_ffi.py --check   (exit 1 if the committed file differs)

The bindings are committed so that building homura needs neither bindgen nor libclang. Run this
after every change to the header; `--check` is part of the local quality gate.
"""
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = ROOT / "csrc" / "homura_rocm.h"
OUT = ROOT / "src" / "backend" / "rocm" / "ffi.rs"

PREAMBLE = """\
//! Bindings to `csrc/homura_rocm.h`, generated by `tools/gen_rocm_ffi.py` with the bindgen CLI.
//! Do not edit by hand: change the header and rerun the script.

#![allow(non_camel_case_types, dead_code)]
"""


def clang_include() -> list[str]:
    """`-isystem` for the clang resource headers (stddef.h): bindgen's libclang may not find them."""
    candidates = sorted(pathlib.Path("/usr/lib/clang").glob("*/include"))
    candidates += sorted(pathlib.Path("/opt/rocm").glob("*/lib/llvm/lib/clang/*/include"))
    for c in candidates:
        if (c / "stddef.h").exists():
            return ["-isystem", str(c)]
    return []


def generate() -> str:
    cmd = [
        "bindgen",
        str(HEADER),
        "--rust-target", "1.88",
        "--rust-edition", "2024",
        "--use-core",
        "--no-layout-tests",
        "--no-doc-comments",
        "--allowlist-function", "hmr_.*",
        "--allowlist-type", "hmr_.*",
        "--allowlist-var", "HMR_.*",
        "--default-macro-constant-type", "signed",
        "--merge-extern-blocks",
        "--",
        *clang_include(),
    ]
    out = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    # Drop bindgen's own header comment, which names its version.
    lines = [line for line in out.splitlines() if not line.startswith("/* automatically generated")]
    body = "\n".join(lines).strip() + "\n"
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout", "--quiet"],
        input=PREAMBLE + "\n" + body,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return formatted


def main() -> int:
    text = generate()
    if sys.argv[1:] == ["--check"]:
        if OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run tools/gen_rocm_ffi.py")
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    if sys.argv[1:]:
        print(__doc__)
        return 2
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
